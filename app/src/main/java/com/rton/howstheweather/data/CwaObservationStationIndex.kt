internal object CwaObservationStationIndex {
    fun nearest(target: GeoPoint, limit: Int): List<CwaObservationStation> {
        if (limit <= 0) return emptyList()
        return stations.asSequence()
            .map { station -> station to approximateDistanceSquared(target, station.coordinate) }
            .sortedBy(Pair<CwaObservationStation, Double>::second)
            .take(limit)
            .map(Pair<CwaObservationStation, Double>::first)
            .toList()
    }

    private fun approximateDistanceSquared(first: GeoPoint, second: GeoPoint): Double {
        val latitudeDelta = first.latitude - second.latitude
        val meanLatitudeRadians = Math.toRadians((first.latitude + second.latitude) / 2.0)
        val longitudeDelta = (first.longitude - second.longitude) * cos(meanLatitudeRadians)
        return latitudeDelta * latitudeDelta + longitudeDelta * longitudeDelta
    }

